const fs=require('fs');
const path=require('path');
const {pathToFileURL}=require('url');
const {chromium}=require('playwright');
const root=path.resolve(__dirname,'..'),dir=path.join(root,'test-results');
(async()=>{
 const browser=await require('./browser.cjs').launch();
 const page=await browser.newPage({viewport:{width:1440,height:1120},deviceScaleFactor:1});
 const errors=[],requests=[];
 page.on('pageerror',e=>errors.push(e.message));page.on('request',r=>{if(/^https?:/.test(r.url()))requests.push(r.url());});
 await page.goto(pathToFileURL(path.join(root,'preview/prd.html')).href);
 await page.evaluate(()=>Promise.all([...document.images].filter(i=>i.hasAttribute('src')).map(i=>{i.loading='eager';return i.decode().catch(()=>null);})));
 const original=await page.evaluate(()=>({images:[...document.querySelectorAll('main img')].map(i=>({loaded:i.complete&&i.naturalWidth>0,embedded:i.src.startsWith('data:')})),missingAnchors:[...document.querySelectorAll('a[href^="#"]')].filter(a=>!document.getElementById(a.hash.slice(1))).map(a=>a.hash),overflow:document.documentElement.scrollWidth>innerWidth,requirements:document.querySelectorAll('#requirements-table tbody tr').length}));
 if(original.images.some(i=>!i.loaded||!i.embedded)||original.missingAnchors.length||original.overflow||original.requirements!==24)throw new Error('Initial checks failed: '+JSON.stringify(original));
 await page.screenshot({path:path.join(dir,'barkdown-prd-preview.png')});
 await page.locator('.hero .image-button').click();
 if(!await page.locator('#image-dialog').isVisible())throw new Error('Image modal did not open');
 await page.keyboard.press('Escape');
 if(await page.locator('#image-dialog').isVisible())throw new Error('Image modal did not close');
 await page.locator('button[data-priority="P0"]').click();
 if(await page.locator('#requirements-table tbody tr:visible').count()!==19)throw new Error('P0 filter wrong');
 await page.locator('button[data-priority="P1"]').click();
 if(await page.locator('#requirements-table tbody tr:visible').count()!==5)throw new Error('P1 filter wrong');
 await page.locator('button[data-priority="all"]').click();
 await page.locator('button[data-width="wide"]').click();
 if(!await page.locator('[data-intermediate]').isVisible())throw new Error('Wide pane illustration failed');
 await page.locator('button[data-width="focused"]').click();
 if(await page.locator('[data-chat-pane]').isVisible())throw new Error('Focused pane illustration failed');
 await page.locator('button[data-width="compact"]').click();
 await page.locator('.phase').first().locator('summary').click();
 if(await page.locator('.phase').first().getAttribute('open')!==null)throw new Error('Phase accordion failed');
 await page.locator('.phase').first().locator('summary').click();
 await page.locator('#graph').scrollIntoViewIfNeeded();
 await page.locator('#graph-zoom').click();
 await page.locator('#dialog-image').evaluate(i=>i.decode());
 if(!await page.locator('#image-dialog').isVisible())throw new Error('Graph zoom failed');
 await page.keyboard.press('Escape');
 await page.locator('.graph-wrap').screenshot({path:path.join(dir,'barkdown-content-map.png')});
 const desktopChecks={...original,interactionChecks:'image zoom, Escape, P0/P1/all filters, three pane modes, phase accordion passed'};
 await page.setViewportSize({width:390,height:844});
 await page.evaluate(()=>scrollTo(0,0));
 await page.screenshot({path:path.join(dir,'barkdown-prd-mobile.png')});
 const mobile=await page.evaluate(()=>({width:innerWidth,scrollWidth:document.documentElement.scrollWidth,overflow:document.documentElement.scrollWidth>innerWidth}));
 if(mobile.overflow)throw new Error('Mobile page overflow');
 await page.setViewportSize({width:1440,height:1120});
 await page.emulateMedia({media:'print'});
 await page.pdf({path:path.join(dir,'barkdown-prd.pdf'),printBackground:true,preferCSSPageSize:true});
 const result={desktop:desktopChecks,mobile,errors,externalRequests:requests,print:'PDF generated'};
 fs.writeFileSync(path.join(dir,'prd-checks.json'),JSON.stringify(result,null,2));
 console.log(JSON.stringify(result));
 await browser.close();
 if(errors.length||requests.length)process.exit(1);
})().catch(e=>{console.error(e);process.exit(1)});
