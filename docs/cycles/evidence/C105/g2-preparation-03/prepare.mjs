function run(command, args, allowed = [0]) {
  const r = spawnSync(command, args, {encoding:'utf8', windowsHide:true, timeout:60000, maxBuffer:8e6});
  if (r.error || !allowed.includes(r.status)) throw Error(`${command}: ${r.error?.message || r.stderr || r.stdout}`);
  return r.stdout;
}
