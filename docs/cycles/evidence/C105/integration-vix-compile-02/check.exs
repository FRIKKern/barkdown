[candidate, behaviour, expected] = System.argv()
unless Code.ensure_loaded?(Vix.Vips.Image) == false, do: raise("Vix must be absent")
Code.compile_file(behaviour)
{_, diagnostics} = Code.with_diagnostics(fn -> Code.compile_file(candidate) end)
errors = Enum.count(diagnostics, &(&1.severity == :error))
if expected == "error" and errors == 0, do: raise("Missing original compiler error")
if expected == "clean" and errors != 0, do: raise("Candidate compiler error")
unless Code.ensure_loaded?(Barkpark.Media.ImageBackend.Vix), do: raise("Backend missing")
unless Barkpark.Media.ImageBackend.Vix.available?() == false, do: raise("Image must be absent")
IO.puts("compiler_errors=#{errors} image_available=false")
