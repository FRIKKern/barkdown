const fs = require('fs');
const path = require('path');
const assert = require('assert/strict');
const { spawn, execFileSync } = require('child_process');
const repository = 'C:/Users/Frikk/Documents/GitHub/barkdown';
const out = repository + '/docs/cycles/evidence/C108/verify-03';
assert(!fs.existsSync(out));
fs.mkdirSync(out);
const head = execFileSync('git', ['rev-parse', 'HEAD'], { cwd: repository, encoding: 'utf8' }).trim();
assert.equal(head, '2eaec9ce3f324c03e7adfcad7267d527807a2d54');
assert.equal(execFileSync('git', ['diff', '--name-only', '--', 'app', 'package-lock.json'], { cwd: repository, encoding: 'utf8' }).trim(), '');
const inputTree = execFileSync('git', ['write-tree'], {cwd: repository, encoding: 'utf8'}).trim();
assert.equal(execFileSync('git', ['diff', '--name-only'], {cwd: repository, encoding: 'utf8'}).trim(), '');
const started = Date.now();
const result = { status: 'running', startedAt: new Date(started).toISOString(), source: head, testedStagedInputTree: inputTree, scope: 'Full current root after bounded managed environment/source/native writer-readiness evidence. App/installer/dependency/pin/capture inputs unchanged.', command: 'npm run verify', cwd: repository };
fs.writeFileSync(out + '/result.json', JSON.stringify(result, null, 2) + '\n');
fs.copyFileSync(__filename, out + '/producer.cjs');
const log = path.join(__dirname, 'C108-root03-389.raw.log');
const fd = fs.openSync(log, 'wx');
const child = spawn('cmd.exe', ['/d', '/s', '/c', 'npm run verify'], { cwd: repository, windowsHide: true, stdio: ['ignore', fd, fd] });
child.on('error', error => { result.error = error.message; });
child.on('close', (exitCode, signal) => {
  fs.closeSync(fd);
  Object.assign(result, { status: exitCode === 0 && !signal && !result.error ? 'passed' : 'failed', exitCode, signal, elapsedMs: Date.now() - started, finishedAt: new Date().toISOString() });
  fs.writeFileSync(out + '/result.json', JSON.stringify(result, null, 2) + '\n');
  const bytes = fs.readFileSync(log);
  fs.writeFileSync(out + '/verify.log.captured-base64.txt', (bytes.toString('base64').match(/.{1,76}/g) || []).join('\n') + '\n');
  fs.writeFileSync(out + '/verify.log', bytes.toString('utf8').replace(/\r\n?/g, '\n').split('\n').map(line => line.replace(/[\t ]+$/, '')).join('\n').replace(/\n*$/, '\n'));
  console.log(JSON.stringify(result));
  if (result.status !== 'passed') process.exitCode = 1;
});
