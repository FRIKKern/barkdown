import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import assert from 'node:assert/strict';
import { coldEvidence, retainEvidence } from './visual-retain.mjs';
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'barkdown-retention-'));
const put = (name, value) => { const file = path.join(root, name); fs.mkdirSync(path.dirname(file), { recursive: true }); fs.writeFileSync(file, typeof value === 'string' ? value : JSON.stringify(value) + '\n'); };
const run = n => `docs/visual/runs/2026-10-0${n}T00-00-00-000Z`;
for (const n of [1, 2, 3, 4, 5]) { put(run(n) + '/manifest.json', { environment: { platform: 'win32' } }); put(run(n) + '/frame.png', `fixture media ${n}`); }
put('docs/visual/approved.json', { manifest: run(2) + '/manifest.json', report: run(2) + '/comparison.json' });
put(run(2) + '/comparison.json', { baseline: run(1) + '/manifest.json' });
put('docs/visual/pending.json', { run: run(5).split('/').at(-1) });
put('docs/images/status/manifest.json', { capturedAt: '5', shots: [{ file: 'paper.55555555.png' }] });
put('docs/images/status/history/2026-10-05T00-00-00-000Z.json', { capturedAt: '5', shots: [{ file: 'paper.55555555.png' }] });
put('docs/images/status/history/2026-10-04T00-00-00-000Z.json', { capturedAt: '4', shots: [{ file: 'paper.44444444.png' }] });
for (const n of [3, 4, 5]) put(`docs/images/status/paper.${String(n).repeat(8)}.png`, `fixture status ${n}`);
put(run(3) + '/partial.log', 'failed capture remains\r\n');
assert.deepEqual(coldEvidence(root), ['docs/images/status/paper.33333333.png', run(3) + '/frame.png', run(3) + '/manifest.json', run(3) + '/partial.log'].sort());
const original = fs.readFileSync(path.join(root, run(3), 'partial.log'));
assert.throws(() => retainEvidence(root, { check: true }), /preserving inventory/);
const first = retainEvidence(root);
assert.equal(first.deleted, 0); assert.equal(first.newlyInventoried, 4);
assert.deepEqual(fs.readFileSync(path.join(root, run(3), 'partial.log')), original);
assert.equal(retainEvidence(root, { check: true }).retainedFiles, 4);
const receipts = fs.readdirSync(path.join(root, 'docs/visual/retention'));
assert.equal(retainEvidence(root).newlyInventoried, 0);
assert.deepEqual(fs.readdirSync(path.join(root, 'docs/visual/retention')), receipts);
put(run(3) + '/late-diagnostic.log', 'new diagnostic');
assert.throws(() => retainEvidence(root, { check: true }), /preserving inventory/);
assert.equal(retainEvidence(root).newlyInventoried, 1);
put(run(3) + '/frame.png', 'changed original');
assert.throws(() => retainEvidence(root), /Retained evidence changed/);
put(run(3) + '/frame.png', 'fixture media 3');
const receiptFile = path.join(root, 'docs/visual/retention', receipts[0]);
const receiptBytes = fs.readFileSync(receiptFile);
fs.appendFileSync(receiptFile, ' ');
assert.throws(() => retainEvidence(root, { check: true }), /Retention receipt changed/);
fs.writeFileSync(receiptFile, receiptBytes);
const frame = path.join(root, run(3), 'frame.png'), retained = path.join(root, run(3), 'retained-frame.png');
fs.renameSync(frame, retained);
assert.throws(() => retainEvidence(root, { check: true }), /ENOENT/);
fs.renameSync(retained, frame);
fs.symlinkSync(os.tmpdir(), path.join(root, run(3), 'escape'), process.platform === 'win32' ? 'junction' : 'dir');
assert.throws(() => retainEvidence(root), /Linked evidence path/);
console.log('Picture retention: original bytes/links preserved, active baseline and previous status retained, idempotence, additions, tampering and linked-path refusal pass. Fixture:', root);
