import assert from 'node:assert/strict';
import { JSDOM } from 'jsdom';
const dom = new JSDOM('<div id="app"><nav id="pages"></nav><div id="bw-toasts"></div></div>', {url:'http://localhost'});
dom.window.addEventListener('error', event => { throw event.error; });
globalThis.window=dom.window; globalThis.document=dom.window.document;
window.barkdown={state:{save:async()=>{}}};
const {state,serialise}=await import('../renderer/src/state.js');
const {ensurePages,seedTree,renderPages,addPage}=await import('../renderer/src/pages.js');
const host=document.getElementById('pages');
let opened=null, imported=null;
const deps={isOpen:()=>false,openKey:(id,source)=>{opened={id,source};},onImport:id=>{imported=id;},onNewPage:()=>{},onNewSubpage:()=>{},openBeside:()=>{}};
const render=()=>renderPages(host,deps);
state.settings={barkpark:{enabled:true}};
state.documents=[{id:'mine',title:'My page'}];
state.barkparkDocs=[{id:'alpha',title:'Alpha paper'},{id:'beta',title:'Beta paper'}];
state.pages=null; seedTree(); render();
assert.deepEqual(state.pages.roots,['mine']);
assert.equal(host.querySelector('#bw-cloud-archive'),null,'cloud archive starts collapsed');
host.querySelector('#bw-cloud-archive-toggle').click();
assert.equal(host.querySelectorAll('#bw-cloud-archive .bw-page-row').length,2);
host.querySelector('#bw-cloud-archive [data-open="bp:alpha"]').click();
assert.deepEqual(opened,{id:'alpha',source:'barkpark'});
assert.deepEqual(state.pages.roots,['mine'],'opening never places a paper');
host.querySelector('#bw-cloud-archive [data-place="bp:alpha"]').click();
assert.deepEqual(state.pages.roots,['mine','bp:alpha']);
addPage('bp:beta','mine');render();
assert.deepEqual(state.pages.children.mine,['bp:beta']);
state.barkparkDocs.push({id:'gamma',title:'Gamma paper'});render();
assert.deepEqual(state.pages.roots,['mine','bp:alpha'],'discovery never changes arranged roots');
assert.deepEqual(state.pages.children.mine,['bp:beta']);
const saved=structuredClone(serialise().pages);state.pages=saved;render();
assert.deepEqual(state.pages.roots,['mine','bp:alpha'],'placements survive persistence');
state.barkparkDocs=[];state.settings.barkpark.enabled=false;render();
assert.deepEqual(state.pages.roots,['mine','bp:alpha'],'disconnect preserves placed papers');
assert.deepEqual(state.pages.children.mine,['bp:beta']);
state.settings.barkpark.enabled=true;state.barkparkDocs=[{id:'gamma',title:'Gamma paper'}];render();
host.querySelector('#bw-cloud-archive [data-more="bp:gamma"]').click();
document.querySelector('[data-act="import"]').click();
assert.equal(imported,'gamma');assert.ok(!state.pages.roots.includes('bp:gamma'),'import action does not place cloud original');
state.pages={roots:['mine','bp:loose','bp:group'],children:{mine:['bp:nested'],'bp:group':['bp:child']},expanded:{mine:true,'bp:group':true},seeded:true};
ensurePages();
assert.deepEqual(state.pages.roots,['mine','bp:group']);
assert.deepEqual(state.pages.children,{mine:['bp:nested'],'bp:group':['bp:child']});
assert.deepEqual(state.pages.cloudLayoutMigration.previousRoots,['mine','bp:loose','bp:group']);
addPage('bp:loose');ensurePages();assert.ok(state.pages.roots.includes('bp:loose'),'migration runs only once');
console.log('Page organization checks passed: archive discovery, browse, placement, nesting, refresh, persistence, disconnect, import routing and recoverable migration.');

