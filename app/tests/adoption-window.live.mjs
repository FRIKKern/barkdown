import { _electron as electron } from './lib/playwright.mjs';
import { createRequire } from 'node:module';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import assert from 'node:assert/strict';
import { fixtureFolder } from './lib/fixture-folder.mjs';
const require = createRequire(import.meta.url);
const root = fixtureFolder('bd-adoption-window-');
const fixture = path.join(root, 'main.cjs');
const modulePath = path.resolve('main/adoption-window.js');
fs.writeFileSync(fixture, `const {app}=require('electron');app.setPath('userData',${JSON.stringify(path.join(root, 'userData'))});app.whenReady().then(()=>{global.recovery=require(${JSON.stringify(modulePath)}).createAdoptionWindow({showLibrary:folder=>{global.shown=folder;}});global.choice=global.recovery.choose({status:'staged',actions:['resume','quit'],error:'Interrupted copy <retained> & safe'}).then(value=>{global.result=value;});});`);
const app = await electron.launch({ executablePath: require('electron'), args: [fixture, `--user-data=${path.join(root, 'userData')}`] });
try {
  const page = await app.firstWindow();
  await page.getByRole('button', { name: 'Resume preparation' }).waitFor();
  assert.match(await page.locator('body').innerText(), /Interrupted copy <retained> & safe/);
  assert.equal(await page.locator('script').count(), 0);
  await page.setViewportSize({ width: 420, height: 600 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.getByRole('button', { name: 'Resume preparation' }).click();
  await page.getByRole('heading', { name: 'Preparing your library' }).waitFor();
  assert.equal(await app.evaluate(() => global.result), 'resume');
  assert.equal(await page.locator('button').count(), 0);
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].close());
  assert.equal((await app.windows()).length, 1, 'busy transaction cannot close its recovery window');
  await app.evaluate(() => { global.result = null; global.choice = global.recovery.choose({ status: 'repairable', actions: ['repair-writer', 'quit'] }).then(value => { global.result = value; }); });
  await page.getByRole('heading', { name: 'Repair this library' }).waitFor();
  assert.match(await page.locator('body').innerText(), /same library in the same folder/);
  assert.match(await page.locator('body').innerText(), /save a copy of the ownership records/);
  await page.setViewportSize({ width: 400, height: 380 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.getByRole('button', { name: 'Repair and open library' }).click();
  await page.getByRole('heading', { name: 'Preparing your library' }).waitFor();
  assert.equal(await app.evaluate(() => global.result), 'repair-writer');
  await app.evaluate(() => { global.result = null; global.choice = global.recovery.choose({ status: 'blocked', actions: ['quit'], error: 'Foreign registry retained' }).then(value => { global.result = value; }); });
  await page.getByRole('button', { name: 'Show library folder' }).waitFor();
  assert.match(await page.locator('body').innerText(), /Keep your library files and recovery records together/);
  await page.getByRole('button', { name: 'Show library folder' }).click();
  assert.equal(await app.evaluate(() => global.shown), path.join(root, 'userData'));
  assert.equal(await app.evaluate(() => global.result), null, 'showing the folder cannot approve startup');
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.getByRole('button', { name: 'Quit' }).click();
  assert.equal(await app.evaluate(() => global.result), 'quit');
  assert(!fs.existsSync(path.join(root, 'userData', 'barkdown')));
  assert(!fs.existsSync(path.join(root, 'userData', 'profile-data')));
  console.log('PASS recovery, repair and help actions; escaped error, narrow layout, busy close guard, no library writes');
} finally { await app.evaluate(() => global.recovery.close()); await app.close(); }
