import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { prepareRuntimeBuild } = require('../main/runtime-build');
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'barkdown-runtime-build-'));
const source = path.join(root, 'source'), built = path.join(source, 'api/_build/dev');
const put = (relative, text) => { const file = path.join(built, relative); fs.mkdirSync(path.dirname(file), { recursive: true }); fs.writeFileSync(file, text); };
put('lib/barkpark/ebin/barkpark.app', 'compiled app fixture');
put('lib/barkpark/ebin/Elixir.Fixture.beam', 'compiled beam fixture');
put('lib/barkpark/priv/migrations/1.exs', 'migration fixture');
put('lib/barkpark/.mix/compile.app_tracer', 'source metadata');
const a = await prepareRuntimeBuild(source, path.join(root, 'A')), b = await prepareRuntimeBuild(source, path.join(root, 'B'));
assert.notEqual(a.path, b.path); assert.equal(a.fingerprint, b.fingerprint);
assert.equal(fs.readFileSync(path.join(a.path, 'lib/barkpark/priv/migrations/1.exs'), 'utf8'), 'migration fixture');
fs.writeFileSync(path.join(a.path, 'lib/barkpark/.mix/compile.app_tracer'), 'private metadata');
assert.equal(fs.readFileSync(path.join(built, 'lib/barkpark/.mix/compile.app_tracer'), 'utf8'), 'source metadata');
assert.equal((await prepareRuntimeBuild(source, path.join(root, 'A'))).path, a.path);
console.log('PASS independent build paths preserve source bytes and allow only private Mix metadata updates');
fs.writeFileSync(path.join(a.path, 'lib/barkpark/ebin/Elixir.Fixture.beam'), 'corrupt');
await assert.rejects(prepareRuntimeBuild(source, path.join(root, 'A')), /payload changed/);
assert.equal(fs.readFileSync(path.join(b.path, 'lib/barkpark/ebin/Elixir.Fixture.beam'), 'utf8'), 'compiled beam fixture');
console.log('PASS changed compiled payload fails reuse without affecting another profile');
await assert.rejects(prepareRuntimeBuild(source, path.join(root, 'interrupted'), { checkpoint: () => { put('lib/barkpark/ebin/Elixir.Fixture.beam', 'newly compiled source'); } }), /source changed/);
assert.ok(fs.readdirSync(path.join(root, 'interrupted/runtime-build')).some(name => name.startsWith('staging-')));
assert.notEqual((await prepareRuntimeBuild(source, path.join(root, 'B'))).fingerprint, b.fingerprint);
console.log('PASS concurrent source changes stop publication and new build identity preserves old cache');
const outside = path.join(root, 'outside'); fs.mkdirSync(outside);
fs.symlinkSync(outside, path.join(root, 'redirect'), process.platform === 'win32' ? 'junction' : 'dir');
await assert.rejects(prepareRuntimeBuild(source, path.join(root, 'redirect/nested')), /Linked runtime/);
assert.deepEqual(fs.readdirSync(outside), []);
console.log('PASS linked destination refuses copy; fixtures retained at ' + root);
