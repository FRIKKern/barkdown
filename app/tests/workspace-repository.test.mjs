import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import crypto from 'node:crypto';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { createProfileRegistry } = require('../main/profile-registry');
const { createWorkspaceRepository } = require('../main/workspace-repository');
const { createStore } = require('../main/store');
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'barkdown-workspace-repo-'));
const registry = createProfileRegistry(path.join(root, 'registry'));
const a = registry.createProfile({ name: 'A' }), b = registry.createProfile({ name: 'B' });
const repo = createWorkspaceRepository({ registry });
const view = text => ({ version: 1, chats: { same: { id: 'same', title: text, messages: [], tabs: [], draft: text + ' draft', folder: null } }, order: ['same'], current: 'same', favorites: [], mode: 'chat' });
repo.saveView(a.id, view('A')); repo.saveView(b.id, view('B'));
const checks = [];
const request = { profileId: a.id, chatId: 'same', attemptId: crypto.randomUUID(), prompt: 'Work in A', provider: 'api', images: [] };
const resolved = { scope: { profileId: a.id } };
const first = repo.begin(request, resolved);
assert.equal(first.fresh, true); assert.deepEqual(first.history, [{ role: 'user', content: 'Work in A' }]);
const replay = repo.begin(request, resolved);
assert.equal(replay.fresh, false); assert.deepEqual(replay.history, first.history);
assert.equal(repo.load(a.id).chats.same.messages.length, 2);
assert.throws(() => repo.begin({ ...request, prompt: 'different' }, resolved), /reused/);
assert.throws(() => repo.begin(request, { scope: { profileId: b.id } }), /owner mismatch/);
checks.push('durable attempt reservation is idempotent and rejects changed work/owner');

const event = (sequence, type, extra = {}) => ({ profileId: a.id, chatId: 'same', runId: 'run-A', sequence, type, provider: 'api', ...extra });
repo.event(request, event(1, 'text_delta', { text: 'Hello A' }));
repo.saveView(a.id, { ...view('A'), chats: { same: { ...view('A').chats.same, messages: [{ role: 'assistant', text: 'stale overwrite' }], draft: 'new A draft' } } });
assert.equal(repo.load(a.id).chats.same.messages.at(-1).text, 'Hello A');
assert.equal(repo.load(a.id).chats.same.draft, 'new A draft');
registry.selectProfile(b.id);
repo.event(request, event(2, 'text_delta', { text: ' still A' }));
assert.equal(repo.load(b.id).chats.same.draft, 'B draft');
assert.equal(repo.load(b.id).chats.same.messages.length, 0);
assert.equal(repo.event(request, event(2, 'text_delta', { text: ' duplicate' })).accepted, false);
assert.throws(() => repo.event(request, event(4, 'text_delta', { text: 'gap' })), /sequence gap/);
assert.throws(() => repo.event(request, event(3, 'text_delta', { profileId: b.id })), /owner mismatch/);
assert.throws(() => repo.event(request, event(3, 'text_delta', { runId: 'run-B' })), /run changed/);
checks.push('late A events preserve B draft and stale renderer cannot overwrite transcript');

repo.event(request, event(3, 'tool_start', { tool: 'read_document', input: { id: 'same' }, toolUseId: 'read' }));
repo.event(request, event(4, 'tool_result', { toolUseId: 'read', ok: true, output: 'A content' }));
repo.event(request, event(5, 'approval', { approvalId: 'approval', request: { kind: 'write_file', path: 'a.txt' } }));
repo.event(request, event(6, 'activity', { label: 'Opened A', target: { kind: 'doc', id: 'same' } }));
repo.event(request, event(7, 'done', { session: 'session-A', history: [{ role: 'user', content: 'Work in A' }, { role: 'assistant', content: 'Hello A still A' }] }));
assert.equal(repo.load(a.id).chats.same.runId, 'run-A', 'done event is not driver-finalization proof');
assert.throws(() => repo.finish(request, { runId: 'run-A', status: 'completed' }), /acknowledgement/);
assert.deepEqual(repo.finish(request, { runId: 'run-A', status: 'completed', driverFinished: true }), { fresh: true, state: 'completed' });
assert.equal(repo.finish(request, { runId: 'run-A', status: 'completed', driverFinished: true }).fresh, false);
const restarted = createWorkspaceRepository({ registry: createProfileRegistry(path.join(root, 'registry')) });
const stored = restarted.load(a.id).chats.same;
assert.equal(stored.messages.at(-1).text, 'Hello A still A');
assert.equal(stored.messages.at(-1).tools[0].output, 'A content');
assert.equal(stored.messages.at(-1).approvals[0].approvalId, 'approval');
assert.equal(stored.messages.at(-1).events[0].label, 'Opened A');
assert.equal(stored.sessions.api, 'session-A'); assert.equal(stored.runId, null);
assert.throws(() => restarted.event(request, event(8, 'text_delta')), /finalized/);
checks.push('tools approvals activity session/history and finalization survive repository restart');

const goal = { id: crypto.randomUUID(), profileId: a.id, coordinatorChatId: 'same' };
repo.stageWorkerChats(goal, [{ chatId: 'worker', title: 'Worker', folder: '/fixture' }]);
const staged = repo.load(a.id), stagedDraft = staged.chats.same.draft;
assert.equal(staged.chats.worker.parent, 'same');
assert.equal(staged.chats.worker.goalId, goal.id);
assert.throws(() => repo.stageWorkerChats({ ...goal, id: crypto.randomUUID() }, [{ chatId: 'worker' }]), /another parent or goal/);
repo.saveView(a.id, view('A old snapshot')); // stale snapshot lacks worker
assert(repo.load(a.id).chats.worker);
repo.stageWorkerChats(goal, [{ chatId: 'worker', title: 'ignored rename' }]);
assert.equal(repo.load(a.id).chats.worker.title, 'Worker');
const workerRequest = { ...request, chatId: 'worker', coordinatorChatId: 'same', goalId: goal.id, taskId: crypto.randomUUID(), attemptId: crypto.randomUUID(), prompt: 'Worker task' };
repo.begin(workerRequest, resolved);
assert.equal(repo.finish(workerRequest, { status: 'interrupted', driverFinished: false }).driverFinished, false);
assert.throws(() => repo.begin({ ...workerRequest, attemptId: crypto.randomUUID() }, resolved), /unfinished/);
assert.equal(repo.load(a.id).chats.same.draft, 'A old snapshot draft');
repo.finish(workerRequest, { status: 'failed', driverFinished: true });
assert.equal(repo.load(b.id).chats.worker, undefined);
checks.push('worker staging is idempotent, profile-scoped and preserved by stale view saves');

let ws = repo.load(a.id);
assert.throws(() => repo.command(a.id, { chatId: 'same', type: 'edit-message', messageId: first.assistantId, text: 'edit', expectedRevision: 0 }), /changed/);
ws = repo.command(a.id, { chatId: 'same', type: 'edit-message', messageId: first.assistantId, text: 'edited', expectedRevision: ws.ownership.revision });
assert.equal(ws.chats.same.messages.at(-1).text, 'edited'); assert.deepEqual(ws.chats.same.sessions, {});
assert.deepEqual(ws.chats.same.messages.at(-1).parts.filter(p => p.kind === 'text').map(p => p.text), ['edited']);
assert(ws.chats.same.messages.at(-1).parts.some(p => p.kind === 'tool'));
ws = repo.command(a.id, { chatId: 'same', type: 'delete-chat', expectedRevision: ws.ownership.revision });
assert(ws.chats.worker, 'deleting parent preserves child');
repo.saveView(a.id, view('old resurrect')); assert.equal(repo.load(a.id).chats.same, undefined);
checks.push('revision-checked explicit transcript actions and parent deletion preserve children and prevent resurrection');

const contextRequest = { ...request, profileId: b.id, attemptId: crypto.randomUUID() };
repo.begin(contextRequest, { scope: { profileId: b.id } });
const moved = repo.load(b.id); moved.chats.same.folder = '/new-folder';
repo.saveView(b.id, moved);
repo.event(contextRequest, { ...event(1, 'done', { session: 'old-folder-session' }), profileId: b.id });
assert.deepEqual(repo.load(b.id).chats.same.sessions, {});
repo.finish(contextRequest, { runId: 'run-A', status: 'completed', driverFinished: true });
checks.push('folder/provider context reset rejects a late old-folder session receipt');

const stable = path.join(root, 'stable'); fs.mkdirSync(stable); fs.writeFileSync(path.join(stable, 'data.json'), '{"owner":"A"}');
const bound = createStore(stable, { create: false });
fs.renameSync(stable, stable + '-retained');
fs.symlinkSync(registry.storeFor(b.id).storeDir, stable, process.platform === 'win32' ? 'junction' : 'dir');
assert.throws(() => bound.readJson('workspace.json', null), /symbolic link/);
assert.throws(() => createStore(path.join(stable, 'child'), { create: false }), /symbolic link/);
const replaced = path.join(root, 'replaced'); fs.mkdirSync(replaced); const second = createStore(replaced, { create: false });
fs.renameSync(replaced, replaced + '-retained'); fs.mkdirSync(replaced);
assert.throws(() => second.writeJson('new.json', {}), /root changed/);
checks.push('bound handles reject ancestor links and root replacement without touching redirected profile');
console.log(JSON.stringify({ checks, root, retained: true }));
