import { openFixturePaper } from './lib/paper-fixture.mjs';
import { connectPaperFixture } from './lib/paper-fixture.mjs';
import { _electron as electron } from 'playwright';
import { createRequire } from 'module';
import fs from 'fs'; import os from 'os'; import path from 'path';
const require = createRequire(import.meta.url);
const SLUG = 'barkdown-editor-test';
import { bp, publishFixture } from './lib/paper-fixture.mjs';
publishFixture({ slug: SLUG, title: 'Code fence checks', description: 'Scratch paper for the Barkdown code-block checks: the fence, the language, keyboard exits and the server round trip; rewritten on every run of tests/editor-code.live.mjs.', blocks: [{ type: 'heading', level: 1, text: 'Code probe' }, { type: 'paragraph', content: [{ type: 'text', value: 'Start here.' }] }] });
const userData = fs.mkdtempSync(path.join(os.tmpdir(), 'bd-code-'));
const app = await electron.launch({ executablePath: require('electron'), args: [path.resolve('.'), `--user-data=${userData}`], env: { ...process.env, BARKDOWN_PROVIDER: 'api', ANTHROPIC_API_KEY: '' } });
const page = await app.firstWindow();
const errors = []; page.on('pageerror', e => errors.push(e.message));
await page.waitForSelector('#bw-pages .bw-page-row');
await page.setViewportSize({ width: 1400, height: 900 });
await connectPaperFixture(page);
await page.waitForFunction(() => window.__barkdown.state.barkparkDocs.length > 0, null, { timeout: 90000 });
await openFixturePaper(page, SLUG);
await page.waitForSelector('.bw-paper-pane:not([hidden]) bp-paper-canvas .ProseMirror', { timeout: 60000 });
await page.waitForFunction(() => (document.querySelector('.bw-paper-pane:not([hidden]) #meta')?.textContent || '').includes('Editing live'), null, { timeout: 30000 });
const shape = () => page.evaluate(() => document.querySelector('.bw-paper-pane:not([hidden]) bp-paper-canvas')._editor.getJSON().content.map(n => n.type + ':' + (n.attrs?.value != null ? JSON.stringify(n.attrs.value) : (n.content || []).map(x => x.text || '').join(''))));
const active = () => page.evaluate(() => document.activeElement?.className || document.activeElement?.tagName);
const pm = page.locator('.bw-paper-pane:not([hidden]) bp-paper-canvas .ProseMirror');
await pm.locator('p').last().click(); await page.keyboard.press('End'); await page.keyboard.press('Enter');
await page.keyboard.type('```'); await page.waitForTimeout(150);
console.log('after fence: active =', await active());
await page.keyboard.type('code();'); await page.keyboard.press('Enter'); await page.keyboard.type('more();');
await page.waitForTimeout(700);
console.log('typed into code:', await shape());
await page.keyboard.press('ArrowDown'); await page.waitForTimeout(150);
console.log('after ArrowDown: active =', await active());
await page.keyboard.type('after the code'); await page.waitForTimeout(300);
console.log('paragraph after code:', await shape());
await page.keyboard.press('ArrowUp'); await page.keyboard.press('ArrowUp'); await page.waitForTimeout(150);
console.log('ArrowUp twice back into code: active =', await active());
await page.keyboard.press('Control+a'); await page.keyboard.press('Backspace'); await page.keyboard.press('Backspace'); await page.waitForTimeout(300);
console.log('backspace on empty code turns into paragraph:', await shape(), 'active =', await active());
await page.waitForFunction(() => /Saved · rev \d+/.test(document.querySelector('.bw-paper-pane:not([hidden]) #save-state')?.textContent || ''), null, { timeout: 20000 }).catch(() => {});
console.log('save:', await page.locator('.bw-paper-pane:not([hidden]) #save-state').innerText(), 'errors:', errors);
await app.close(); fs.rmSync(userData, { recursive: true, force: true });
