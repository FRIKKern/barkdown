// Private real API proof; the native UI journey is tested separately.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import net from 'node:net';
import crypto from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { LocalBarkpark } = require('../main/local-barkpark');
const { SourceDriver } = require('../main/local-barkpark-source');
const { createDraftNotes } = require('../main/draft-notes');
const { createStore } = require('../main/store');
const bp = require('../main/barkpark');
const source = process.env.BARKDOWN_TEST_BP_SOURCE;
if (!source) throw Error('Explicit disposable runtime source required');
const root = path.resolve('..'), data = fs.mkdtempSync(path.join(os.tmpdir(), 'bd-note-contract-'));
const git = (args, cwd = root) => execFileSync('git', args, { cwd, encoding: 'utf8' }).trim();
const free = () => new Promise(resolve => { const s = net.createServer(); s.listen(0, '127.0.0.1', () => { const p = s.address().port; s.close(() => resolve(p)); }); });
const port = await free(); let pgPort = await free(); while (port === pgPort) pgPort = await free();
const secrets = { password: crypto.randomBytes(32).toString('hex'), token: 'bp_admin_' + crypto.randomBytes(24).toString('base64url') };
const runtime = new LocalBarkpark(new SourceDriver({ source, port, pgPort }, data, secrets));
const config = { enabled: true, writes: true, server: `http://127.0.0.1:${port}`, token: secrets.token, dataset: 'production' };
const profileId = crypto.randomUUID(); config.managedProfileId = profileId;
const store = createStore(path.join(data, 'agent-store'));
const { createPaperTools } = require('../main/paper-tools');
const { createDocuments } = require('../main/documents');
const { createAgentEdits } = require('../main/agent-edits');
const { Client } = await import('@modelcontextprotocol/sdk/client/index.js');
const { StdioClientTransport } = await import('@modelcontextprotocol/sdk/client/stdio.js');
const tools = createPaperTools({ store, connection: config, profileId });
const edits = () => createAgentEdits({ store: createStore(store.dir()), documents: createDocuments(store) });
const results = [], report = { host: git(['rev-parse', 'HEAD']), upstream: git(['rev-parse', 'HEAD'], source), sourceDirty: git(['status','--porcelain','--','app']) !== '', results, failure: null };
let client;
runtime.on('status', s => console.log('Private agent-note runtime:', s.phase, s.error || ''));
try {
  await runtime.start(); await runtime.ready();
  const requestId = crypto.randomUUID(), initial = { title: 'Agent notebook', markdown: 'Saffron **original** body.', requestId };
  const created = await tools.create(initial), id = 'bp:' + created.id;
  assert.equal(created.title, initial.title); assert.equal(created.blocks[0].locked, true);
  assert.match(created.markdown, /Saffron \*\*original\*\*/);
  assert.equal((await tools.create(initial)).id, created.id);
  await assert.rejects(tools.create({ ...initial, markdown: 'Replacement attempt' }), /different content/);
  assert((await tools.list()).some(p => p.id === created.id)); assert((await tools.search('Saffron')).some(p => p.id === created.id));
  assert.equal(store.list('documents','.json').length, 0);
  results.push('Owned tool creation writes one real draft with title/body; replay preserves identity; different intent refuses; complete discovery/body search find it without a legacy file');
  const replaced = await edits().apply({ id, mode: 'replace', markdown: 'Agent replacement.', baseRev: created.rev, summary: 'Replace the body' }, config);
  const after = await tools.get(created.id); assert.equal(after.title, initial.title); assert.deepEqual(after.blocks[0], created.blocks[0]);
  assert.match(after.markdown, /Agent replacement/);
  await edits().undo(id, replaced.id, config);
  assert.deepEqual((await tools.get(created.id)).blocks, created.blocks);
  await assert.rejects(edits().undo(id, replaced.id, { ...config, token: 'foreign' }), /another or unknown/);
  results.push('Real guarded body replacement preserves locked title; reconstructed service/receipt Undo restores exact blocks; foreign connection refuses before write');
  const beforeAppend = await tools.get(created.id);
  const appended = await edits().apply({ id, mode: 'append', markdown: 'Agent addition.', baseRev: beforeAppend.rev, summary: 'Append' }, config);
  await bp.applyOps(config, created.id, [{op:'patch-block',id:'tpl-title',patch:{text:'Human owns this title'}}], appended.afterRev);
  await assert.rejects(edits().undo(id, appended.id, config), /changed since/);
  assert.equal((await tools.get(created.id)).title, 'Human owns this title');
  results.push('Later real human title revision blocks Undo and preserves acknowledged human content');
  const transport = new StdioClientTransport({ command: process.execPath, args: [path.resolve('main/mcp-server.js'), store.dir()], env: { ...process.env, BARKDOWN_RUN_CONNECTION: JSON.stringify(config), BARKDOWN_PROFILE_ID: profileId } });
  client = new Client({ name:'agent-note-proof', version:'1' }); await client.connect(transport);
  const call = async (name, args) => { const r = await client.callTool({name,arguments:args}); assert(!r.isError,JSON.stringify(r)); return r.content[0].text; };
  const mcpRequest = crypto.randomUUID(), mcpId = 'drafts.bd-note-' + mcpRequest;
  assert.match(await call('create_document',{title:'MCP notebook',markdown:'MCP original body.',requestId:mcpRequest}), /Created document bp:drafts\./);
  assert((JSON.parse(await call('list_documents',{}))).some(p=>p.id==='bp:'+mcpId));
  assert((JSON.parse(await call('search_documents',{query:'MCP original'}))).some(p=>p.id==='bp:'+mcpId));
  const mcpBefore = await tools.get(mcpId);
  await call('read_document',{id:'bp:'+mcpId,format:'structured'});
  await call('edit_document',{id:'bp:'+mcpId,mode:'replace_block',blockIndex:1,markdown:'MCP edited body.',summary:'Clarify the body'});
  assert.match((await tools.get(mcpId)).markdown,/MCP edited body/);
  const receipt=edits().latest('bp:'+mcpId,config);
  await client.close(); client=null;
  await edits().undo('bp:'+mcpId,receipt.id,config);
  assert.deepEqual((await tools.get(mcpId)).blocks,mcpBefore.blocks);
  assert.equal(store.list('documents','.json').length, 0); // Managed tools never seed or create legacy notes.
  results.push('Actual stdio MCP create/list/search/read/edit writes the same owned draft; Undo after MCP exit restores exact prior blocks');
  console.log('PASS',results);
} catch(error) { report.failure=error.stack; throw error; }
finally {
  await client?.close(); await runtime.stop();
  const out=path.join(root,'docs/cycles/evidence/C069'); fs.mkdirSync(out,{recursive:true});
  const file=path.join(out,`agent-contract-${Date.now()}.json`); fs.writeFileSync(file,JSON.stringify(report,null,2)+'\n');
  console.log('Agent note evidence:',file,'Retained data:',data);
}
