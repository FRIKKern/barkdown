import { _electron as electron } from 'playwright';
import { createRequire } from 'node:module';
import fs from 'node:fs'; import os from 'node:os'; import path from 'node:path';
import assert from 'node:assert/strict';
const require = createRequire(import.meta.url);
const userData = fs.mkdtempSync(path.join(os.tmpdir(), 'bd-side-ui-'));
const parentFolder = path.join(userData,'parent'), childFolder = path.join(userData,'child');
fs.mkdirSync(parentFolder); fs.mkdirSync(childFolder); fs.writeFileSync(path.join(childFolder,'note.txt'),'Child-owned file');
const app = await electron.launch({executablePath:require('electron'),args:[path.resolve('.'), '--legacy',`--user-data=${userData}`],env:{...process.env,BARKDOWN_PROVIDER:'api',ANTHROPIC_API_KEY:''}});
const page=await app.firstWindow(), errors=[];
page.on('pageerror',e=>errors.push(e.message));
try {
  await page.waitForFunction(()=>window.__barkdown?.state.loaded);
  await page.setViewportSize({width:1600,height:1000});
  await app.evaluate(({ipcMain}, folder)=>{
    globalThis.sideRequests=[];
    ipcMain.removeHandler('app:pickFolder'); ipcMain.handle('app:pickFolder',()=>folder);
    ipcMain.removeHandler('agent:start'); ipcMain.handle('agent:start',(event,input)=>{
      globalThis.sideRequests.push(input);
      const runId='side-ui-run';
      setTimeout(()=>{ event.sender.send('agent:event',{chatId:input.chatId,runId,type:'text_delta',text:'A reply in this conversation.'}); event.sender.send('agent:event',{chatId:input.chatId,runId,type:'done',provider:input.provider}); },150);
      return {runId};
    });
  },childFolder);
  const parent=await page.evaluate(folder=>{const s=window.__barkdown.state,c=s.chats[s.current];Object.assign(c,{title:'Parent conversation',folder,provider:'codex',model:'parent-model',effort:'high',draft:'Parent draft'});window.__barkdown.render();return c.id;},parentFolder);
  await page.locator('#bw-open-work').click(); await page.locator('[data-new="chat"]').click();
  const side=page.locator('.bw-side-chat'); await side.waitFor();
  const child=await page.evaluate(()=>{const s=window.__barkdown.state,c=s.chats[s.current];return c.tabs.find(t=>t.id===c.active).sideChatId;});
  let childState=await page.evaluate(id=>window.__barkdown.state.chats[id],child);
  assert.equal(childState.folder,parentFolder);assert.equal(childState.parent,parent);assert.equal(childState.model,'parent-model');
  assert.equal(await page.locator(`#bw-recent-chats [data-context="${child}"]`).count(),1);
  for(const name of ['provider','model','effort','attach','folder-context']) assert.ok(await side.locator(`[data-composer="${name}"]`).isVisible());
  await side.locator('[data-composer="provider"]').click(); await page.locator('.bw-menu:not([hidden]) [data-choice="claude"]').click();
  assert.equal(await page.evaluate(id=>window.__barkdown.state.chats[id].provider,parent),'codex');
  await side.locator('[data-composer="provider"]').click(); await page.locator('.bw-menu:not([hidden]) [data-choice="codex"]').click();
  await side.locator('[data-composer="model"]').click(); await page.locator('.bw-menu:not([hidden]) [data-custom]').click();
  await page.locator('.bw-ask input').fill('side-model'); await page.locator('.bw-ask button[type="submit"]').click();
  await side.locator('[data-composer="effort"]').click(); await page.locator('.bw-menu:not([hidden]) [data-choice="low"]').click();
  await side.locator('[data-composer="folder-context"]').click(); await page.locator('.bw-menu:not([hidden]) [data-act="choose"]').click();
  await page.waitForFunction(({child,folder})=>window.__barkdown.state.chats[child].folder===folder,{child,folder:childFolder});
  assert.equal(await page.evaluate(id=>window.__barkdown.state.chats[id].folder,parent),parentFolder);
  assert.equal(await page.locator('#bw-prompt').inputValue(),'Parent draft');
  await side.locator('[data-composer="attach-input"]').setInputFiles({name:'test.png',mimeType:'image/png',buffer:Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aM3sAAAAASUVORK5CYII=','base64')});
  await side.locator('.bw-attachment').waitFor();
  assert.equal(await page.locator('#bw-attachments .bw-attachment').count(),0);
  await side.locator('textarea').fill('Question from the side'); await side.locator('textarea').press('Enter');
  await side.locator('.bw-user-images img').waitFor();
  await page.waitForFunction(id=>window.__barkdown.state.chats[id].messages.at(-1)?.text.includes('A reply'),child);
  const request=(await app.evaluate(()=>globalThis.sideRequests))[0];
  assert.equal(request.chatId,child);assert.equal(request.context.folder,childFolder);assert.equal(request.options.model,'side-model');assert.equal(request.options.effort,'low');assert.equal(request.images.length,1);
  assert.equal(await page.evaluate(id=>window.__barkdown.state.chats[id].messages.length,parent),0);
  await side.locator('textarea').fill('Child draft');
  await side.locator('#open-chat').click();
  await page.locator('#bw-prompt').fill('Updated while opened fully');
  await page.locator('#bw-transcript [data-parent]').click();
  assert.equal(await side.locator('textarea').inputValue(),'Updated while opened fully','inline view refreshes the shared draft');
  await side.locator('textarea').fill('Child draft');
  await page.screenshot({path:'test-results/sidechat-parity.png'});
  await page.locator('#bw-tabs .bw-tab.active [data-close]').dispatchEvent('click');
  await page.locator(`#bw-recent-chats [data-context="${child}"]`).click();
  assert.equal(await page.locator('#bw-prompt').inputValue(),'Child draft');
  assert.equal(await page.locator('#bw-model-label').innerText(),'side-model');
  await page.locator('#bw-prompt').fill('Draft edited in main view');
  await page.locator('#bw-transcript [data-parent]').click();
  assert.equal(await page.locator('#bw-prompt').inputValue(),'Parent draft');
  await page.locator(`#bw-recent-chats [data-context="${child}"]`).click();
  assert.equal(await page.locator('#bw-prompt').inputValue(),'Draft edited in main view');
  await app.evaluate(({BrowserWindow},chatId)=>BrowserWindow.getAllWindows()[0].webContents.send('agent:event',{chatId,type:'activity',label:'Opened child file',target:{kind:'project',path:'note.txt',title:'note.txt'}}),child);
  await page.locator('#bw-transcript [data-event]').last().click();
  await page.waitForSelector('.cm-content');
  assert.ok((await page.locator('.cm-content').innerText()).includes('Child-owned file'));
  assert.equal(await page.evaluate(id=>window.__barkdown.state.chats[id].tabs.some(t=>t.type==='project'),parent),false);
  await page.waitForTimeout(550);
  // Older saves omitted side chats from navigation; loading should restore them.
  await page.evaluate(async child=>{const data=await window.barkdown.state.load();data.order=data.order.filter(id=>id!==child);await window.barkdown.state.save(data);},child);
  await page.reload(); await page.waitForFunction(()=>window.__barkdown?.state.loaded);
  childState=await page.evaluate(id=>window.__barkdown.state.chats[id],child);
  assert.equal(childState.parent,parent);assert.equal(childState.folder,childFolder);assert.equal(childState.model,'side-model');assert.equal(childState.draft,'Draft edited in main view');assert.equal(childState.messages[0].images.length,1);
  assert.equal(await page.locator(`#bw-recent-chats [data-context="${child}"]`).count(),1);
  assert.deepEqual(errors,[]);
  console.log('Side-chat parity passed: saved navigation, parent link, inherited settings, independent folder/model/effort, image upload and send, captured run context, drafts across views and restart.');
} finally { await app.close(); }

