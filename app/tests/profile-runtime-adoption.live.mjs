// Same-machine disposable cold-copy proof. Never opens a user's library.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import crypto from 'node:crypto';
import net from 'node:net';
import { createRequire } from 'node:module';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { tinyPng } from './png.mjs';
const require = createRequire(import.meta.url);
const { createProfileRegistry } = require('../main/profile-registry');
const { createProfileRuntimePool } = require('../main/profile-runtime');
const { createRuntimeAdoption, assertCold } = require('../main/profile-runtime-adoption');
const { LocalBarkpark } = require('../main/local-barkpark');
const { SourceDriver } = require('../main/local-barkpark-source');
const barkpark = require('../main/barkpark');
const source = path.resolve(process.env.BARKDOWN_TEST_BP_SOURCE || '../../barkpark-editor');
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'barkdown-cold-runtime-'));
const legacy = path.join(root, 'legacy'), data = path.join(legacy, 'local-barkpark/default');
fs.mkdirSync(legacy, { recursive: true });
const freePort = () => new Promise(resolve => { const s = net.createServer(); s.listen(0, '127.0.0.1', () => { const port = s.address().port; s.close(() => resolve(port)); }); });
const config = { source, port: await freePort(), pgPort: await freePort() };
const secrets = { password: crypto.randomBytes(32).toString('hex'), token: 'bp_admin_' + crypto.randomBytes(24).toString('base64url') };
const encode = text => 'plain:' + Buffer.from(text).toString('base64');
fs.writeFileSync(path.join(legacy, 'local-credentials.json'), JSON.stringify({ password: encode(secrets.password), token: encode(secrets.token) }));
fs.writeFileSync(path.join(legacy, 'settings.json'), JSON.stringify({ barkpark: { local: { ...config, enabled: true } } }));
const registry = createProfileRegistry(path.join(root, 'registry'));
const profile = registry.createProfile({ name: 'Adopted fixture' }), store = registry.storeFor(profile.id);
fs.copyFileSync(path.join(legacy, 'local-credentials.json'), path.join(store.storeDir, 'local-credentials.json'));
fs.copyFileSync(path.join(legacy, 'settings.json'), path.join(store.storeDir, 'settings.json'));
const readSecrets = bound => Object.fromEntries(Object.entries(bound.readJson('local-credentials.json')).map(([key, value]) => { assert.ok(value.startsWith('plain:')); return [key, Buffer.from(value.slice(6), 'base64').toString()]; }));
const runtimes = [], drivers = [];
function runtime(descriptor, dataDir, values) {
  const driver = new SourceDriver(descriptor, dataDir, values); drivers.push(driver);
  const service = new LocalBarkpark(driver, { retries: 0 }); runtimes.push(service);
  service.on('status', s => console.log(dataDir === data ? 'source:' : 'destination:', s.phase, s.error || ''));
  return service;
}
const original = runtime(config, data, secrets);
const pool = createProfileRuntimePool({ registry, readSecrets, createRuntime: ({ descriptor, dataDir, secrets }) => runtime(descriptor, dataDir, secrets) });
const adoption = createRuntimeAdoption({ registry, readSecrets });
const connection = { server: `http://127.0.0.1:${config.port}`, token: secrets.token, writes: true, viaCli: false, dataset: 'production' };
const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const git = (args, cwd = repo) => execFileSync('git', args, { cwd, encoding: 'utf8' }).trim();
const report = { startedAt: new Date().toISOString(), barkdownCommit: git(['rev-parse', 'HEAD']), barkdownDirty: git(['status', '--porcelain', '--', 'app/main', 'app/tests/profile-runtime-adoption.live.mjs']) !== '', barkparkCommit: git(['rev-parse', 'HEAD'], source), barkparkDirty: git(['status', '--porcelain'], source) !== '', checks: [], stopped: false, portability: false };
const record = text => { report.checks.push(text); console.log('PASS ' + text); };
let lease;
console.log('Disposable cold-adoption fixture:', root);
try {
  await original.start();
  const tags = await fetch(connection.server + '/v1/data/mutate/production', { method: 'POST', headers: { authorization: 'Bearer ' + connection.token, 'content-type': 'application/json' }, body: JSON.stringify({ mutations: [{ createOrReplace: { _id: 'adoption-fixture', _type: 'tag', title: 'Adoption fixture' } }, { publish: { id: 'adoption-fixture', type: 'tag' } }] }) });
  assert.equal(tags.status, 200, await tags.text());
  const image = path.join(root, 'original.png'); fs.writeFileSync(image, tinyPng(32, 32, [40, 140, 80]));
  const media = await barkpark.uploadMedia(connection, { name: 'original.png', mime: 'image/png', filePath: image });
  await barkpark.publish(connection, { slug: 'cold-note', title: 'Before adoption', description: 'Disposable cold runtime adoption fixture with original absolute media reference.', tags: [{ tag: 'adoption-fixture', strength: 95, rationale: 'Cold runtime adoption verification fixture' }], blocks: [{ type: 'paragraph', content: [{ type: 'text', value: 'Original note content' }] }, { type: 'image', src: media.src, alt: 'Original media', width: 32, height: 32 }] });
  const before = await barkpark.getPaper(connection, 'cold-note');
  await assert.rejects(adoption.adopt({ profileId: profile.id, legacyDir: legacy }), /owned/);
  assert.equal(store.readJson('runtime.json', null), null);
  record('live source refused without descriptor publication or process stop');
  await original.stop(); await assertCold(data);
  const result = await adoption.adopt({ profileId: profile.id, legacyDir: legacy });
  assert.deepEqual(await adoption.adopt({ profileId: profile.id, legacyDir: legacy }), result);
  assert.equal(fs.existsSync(path.join(result.dataDir, 'runtime-build')), false);
  assert.equal(fs.existsSync(path.join(result.dataDir, 'boot-ready')), false);
  record('clean PG18 source copied with verified backup, original credentials/ports and idempotent publication');
  lease = await pool.acquire(profile.id, { ownerId: 'adopted-check', writes: true });
  assert.equal(lease.connection.server, connection.server);
  assert.equal(lease.connection.token, connection.token);
  const after = await barkpark.getPaper(lease.connection, 'cold-note');
  assert.equal(after.title, before.title); assert.equal(after.rev, before.rev); assert.equal(after.markdown, before.markdown);
  assert.deepEqual(Buffer.from(await (await fetch(media.src)).arrayBuffer()), fs.readFileSync(image));
  const edited = await barkpark.applyOps(lease.connection, 'cold-note', [{ op: 'append-block', block: { type: 'paragraph', content: [{ type: 'text', value: 'Adopted-only edit' }] } }], after.rev);
  assert.equal(edited.ok, true);
  await assert.rejects(adoption.rollback({ profileId: profile.id }), /owned/);
  record('adopted real server retains revision/content/absolute media origin; edits save and live rollback refuses');
  await lease.release(); lease = null; await pool.shutdown();
  await adoption.rollback({ profileId: profile.id });
  assert.equal(store.readJson('runtime.json', null), null);
  await original.start();
  const rolledBack = await barkpark.getPaper(connection, 'cold-note');
  assert.equal(rolledBack.markdown, before.markdown); assert.equal(rolledBack.rev, before.rev);
  assert.deepEqual(Buffer.from(await (await fetch(media.src)).arrayBuffer()), fs.readFileSync(image));
  record('rollback retains edited destination and backup; original restarts with unchanged note/revision/media');
} catch (error) { report.error = error.message; throw error; }
finally {
  const errors = [];
  if (lease) await lease.release().catch(e => errors.push(e.message));
  await pool.shutdown().catch(e => errors.push(e.message));
  for (const service of runtimes) await service.stop().catch(e => errors.push(e.message));
  report.stopped = drivers.every(d => !fs.existsSync(path.join(d.pgData, 'postmaster.pid')));
  report.cleanupErrors = errors; report.finishedAt = new Date().toISOString();
  fs.writeFileSync(path.join(root, 'evidence.json'), JSON.stringify(report, null, 2));
  console.log('Evidence retained:', path.join(root, 'evidence.json'));
  if (!report.stopped) throw new Error('Owned fixture database remains; inspect retained data');
}
